#!/usr/bin/env bash
# Copies the Terraform outputs the playbooks need into Ansible group_vars.
set -euo pipefail
cd "$(dirname "$0")/.."

out=ansible/group_vars/all/terraform.yml

terraform -chdir=terraform output -json | python3 -c '
import json, sys

outputs = json.load(sys.stdin)
wanted = {
    "aws_region": "region",
    "asg_name": "asg_name",
    "target_group_arn": "target_group_arn",
    "artifact_bucket": "artifact_bucket",
    "version_parameter": "version_parameter",
}
print("---")
print("# Generated by scripts/export-terraform-outputs.sh -- do not edit.")
for var, output in wanted.items():
    print("%s: %s" % (var, json.dumps(outputs[output]["value"])))
' > "$out"

echo "wrote $out"
